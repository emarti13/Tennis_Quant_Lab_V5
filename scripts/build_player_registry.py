"""Build the player registry and its alias tables from TennisMyLife and OddsPapi.

Usage:
    python scripts/build_player_registry.py --year 2026 --as-of 2026-10-13

Writes context_registry/players/:
    players.csv               one row per player (our own player_id; ids are never reused)
    alias_tennismylife.csv    TennisMyLife id -> player_id
    alias_oddspapi.csv        OddsPapi participant id -> player_id, with status and evidence
    review.csv                everything a person should decide
    REPORT.md                 summary
Rows marked confirmed, user or rejected are kept as they are. Production does not read
these tables yet.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from v5_player_registry import (  # noqa: E402
    ODDS_ALIAS_COLUMNS, PLAYER_COLUMNS, TML_ALIAS_COLUMNS, build_players, link_oddspapi, load_table, load_tml_matches,
)
from v5_tournament_identity import load_crosswalk  # noqa: E402


def _table(frame: pd.DataFrame, cols: list[str], limit: int = 60) -> str:
    if frame.empty:
        return "_None._\n"
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in frame[cols].head(limit).iterrows():
        lines.append("| " + " | ".join(str(r[c]).replace("|", "/") for c in cols) + " |")
    more = f"\n_{len(frame) - limit} more in review.csv._\n" if len(frame) > limit else ""
    return "\n".join(lines) + "\n" + more


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--year", type=int, required=True, help="Season whose OddsPapi fixtures are linked.")
    ap.add_argument("--as-of", required=True)
    ap.add_argument("--out", default="context_registry/players")
    ap.add_argument("--fixtures", default="oddspapi_registry/fixtures.csv")
    ap.add_argument("--crosswalk-dir", default="context_registry/master_schedule")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    matches = load_tml_matches()
    players, alias_tml, review_tml = build_players(
        matches, load_table(out / "players.csv", PLAYER_COLUMNS), load_table(out / "alias_tennismylife.csv", TML_ALIAS_COLUMNS),
        set_on=args.as_of)
    xdir = Path(args.crosswalk_dir)
    alias_odds, review_odds, drift = link_oddspapi(
        pd.read_csv(args.fixtures, low_memory=False), load_crosswalk(xdir / "crosswalk_oddspapi.csv"), matches,
        load_crosswalk(xdir / "crosswalk_tennismylife.csv"), alias_tml, players,
        load_table(out / "alias_oddspapi.csv", ODDS_ALIAS_COLUMNS), year=args.year, set_on=args.as_of)

    review = pd.concat([review_tml, review_odds], ignore_index=True)
    players.to_csv(out / "players.csv", index=False, encoding="utf-8")
    alias_tml.to_csv(out / "alias_tennismylife.csv", index=False, encoding="utf-8")
    alias_odds.to_csv(out / "alias_oddspapi.csv", index=False, encoding="utf-8")
    review.to_csv(out / "review.csv", index=False, encoding="utf-8")

    active = players[players["status"] == "active"]
    multi = alias_tml.groupby("player_id").size()
    shared = alias_odds.groupby("player_id").size().drop(labels=[""], errors="ignore")
    r = [f"# Player registry, {args.year}", "",
         f"As of {args.as_of} · generated by `scripts/build_player_registry.py`.", "",
         "## Summary", "",
         f"- Players: {len(active)} active ({active['tour'].value_counts().to_dict()}); "
         f"{int((multi > 1).sum())} hold more than one TennisMyLife id.",
         f"- TennisMyLife ids: {len(alias_tml)} ({alias_tml['status'].value_counts().to_dict()}).",
         f"- OddsPapi participants seen in {args.year}: {len(alias_odds)} → {alias_odds['status'].value_counts().to_dict()}.",
         f"- OddsPapi links by method: {alias_odds[alias_odds['player_id'] != '']['method'].value_counts().to_dict()}.",
         f"- Players linked from more than one OddsPapi id: {int((shared > 1).sum())}.",
         f"- Review items: {review['kind'].value_counts().to_dict()}.", "",
         "Statuses: confirmed = 2+ shared matches agree; auto = 1 shared match, or a unique exact name; "
         "review = a person decides (no price); no_history = no candidate in our history (never a rating); "
         "placeholder = a draw slot such as WQF1.", "",
         "## Review list", "",
         "### TennisMyLife ids not joined automatically", "",
         _table(review[review["kind"] == "tennismylife_ids"], ["tour", "subject", "names", "reason", "candidates"]),
         "### Kept apart: same name, different people (information)", "",
         _table(review[review["kind"] == "kept_apart"], ["tour", "subject", "names", "reason"]),
         "### OddsPapi participants for a person to decide", "",
         _table(review[review["kind"] == "oddspapi_participant"], ["tour", "subject", "names", "reason", "candidates"]),
         "### Stored links the fresh build would change", "",
         _table(drift, ["participant_id", "stored", "fresh", "fresh_status"]),
         ]
    (out / "REPORT.md").write_text("\n".join(r), encoding="utf-8")
    print(f"Wrote {out}/REPORT.md")
    print(f"players {len(active)} · OddsPapi {alias_odds['status'].value_counts().to_dict()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
